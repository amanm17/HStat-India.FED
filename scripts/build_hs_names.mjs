/*
 * Regenerates src/lib/hsnames.generated.ts from hs_index/parents.csv
 * (curated short names) and config/hs_titles.json (official HS-2/HS-4 text).
 *
 *   node scripts/build_hs_names.mjs
 *
 * The frontend cannot read config/ at runtime and the build script is not
 * changed for this, so the module is committed; qa/suite/homepanels.mjs
 * fails if it falls out of step with the two sources.
 */
import { readFileSync, writeFileSync } from 'node:fs'

export function render() {
  const titles = JSON.parse(readFileSync('config/hs_titles.json', 'utf8'))
  const lines = readFileSync('hs_index/parents.csv', 'utf8')
    .split('\n')
    .filter(line => line.trim() && !line.startsWith('#'))
  /* One CSV row: quoted fields may hold commas ("Dyes, pigments ..."). */
  const cells = line => {
    const out = []
    let cur = '', quoted = false
    for (let i = 0; i < line.length; i += 1) {
      const ch = line[i]
      if (quoted) {
        if (ch === '"' && line[i + 1] === '"') { cur += '"'; i += 1 }
        else if (ch === '"') quoted = false
        else cur += ch
      } else if (ch === '"') quoted = true
      else if (ch === ',') { out.push(cur); cur = '' }
      else cur += ch
    }
    out.push(cur.replace(/\r$/, ''))
    return out
  }
  const header = cells(lines[0])
  const at = name => header.indexOf(name)
  const rows = lines.slice(1).map(cells).map(r => [r[at('code')], r[at('short_name')]])
  const short = Object.fromEntries(rows)
  const codes = Object.keys(titles).sort()
  const missing = codes.filter(code => !short[code])
  if (missing.length) throw new Error(`No short name for ${missing.join(', ')}`)
  const entries = codes.map(code => `  ${JSON.stringify(code)}: [${JSON.stringify(short[code])}, ${JSON.stringify(titles[code])}],`)
  return `/* Generated by scripts/build_hs_names.mjs from hs_index/parents.csv
 * and config/hs_titles.json. Do not edit by hand. */
export const HS_PARENT_NAMES: Record<string, [short: string, official: string]> = {
${entries.join('\n')}
}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('src/lib/hsnames.generated.ts', render())
  console.log('wrote src/lib/hsnames.generated.ts')
}
